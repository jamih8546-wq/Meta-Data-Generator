// Unified server-side AI generation endpoint with Vision capability
app.post('/api/ai/generate', async (req, res) => {
  try {
    const rawProv = (req.body.provider || 'gemini').toLowerCase().trim();
    const provider = rawProv.includes('openrouter')
      ? 'openrouter'
      : rawProv.includes('open')
      ? 'openai'
      : rawProv.includes('claude')
      ? 'claude'
      : rawProv.includes('groq')
      ? 'groq'
      : rawProv.includes('mistral')
      ? 'mistral'
      : 'gemini';
    const { filename, imagePayload, model, apiKey } = req.body;

    const STOCK_SYSTEM_PROMPT = `You are a top-ranked microstock contributor and SEO metadata expert for Adobe Stock, Shutterstock, Freepik, and Vecteezy.
Analyze the provided visual asset (artwork, vector, or image) and generate highly commercial, accurate microstock metadata.
CRITICAL INSTRUCTIONS:
1. You MUST examine the actual visual subject depicted in the image (e.g. apple, orange, lemon, cherries, fruit, animal, object, etc.) and NOT rely solely on generic filename words like "stipple" or "halftone" (which only describe the artistic style).
2. NEVER generate "Solid Black Square", "Plain Dark Backdrop", or generic black textures. If an asset has an artistic style like stipple, engraving, or halftone, it represents a detailed illustration or drawing.
3. "title": 55 to 80 characters, highly descriptive, commercially appealing. State the real subject (e.g. "Fresh Juicy Red Apple with Green Leaf Isolated on White Background").
4. "keywords": Exactly 40 to 49 comma-separated relevant tags. First 10 tags MUST be the specific visual subject, related food/objects, colors, concepts, followed by style/commercial tags. NEVER include numbers like "(1)" or random codes.
5. "description": 1 to 2 complete, well-formed sentences describing the subject, composition, artistic style, and background.
6. "category": Choose the single most fitting microstock category from: [Arts, Arts Backgrounds/Textures, Arts Objects, Arts Nature, Animals/Wildlife, Buildings/Landmarks, Business/Finance, Food and Drink, Healthcare/Medical, Holidays, Illustrations/Clip-Art, Industrial, People, Science/Technology, Signs/Symbols, Sports/Recreation, Transportation, Vintage/Retro].

Return STRICT, VALID JSON ONLY with keys "title", "keywords", "description", "category". Do not wrap with anything else.`;

    const hasImage = Boolean(imagePayload?.base64 && imagePayload?.mimeType);
    const assetContext = `Asset filename: "${filename || 'artwork'}".`;

    // 1. Groq API (if provider is Groq and key provided)
    if (provider === 'groq' && apiKey) {
      try {
        const groqModel = model || 'llama-3.2-11b-vision-preview';
        const isGroqVision = groqModel.includes('vision');
        const userContent: any[] = [];

        if (isGroqVision && hasImage) {
          userContent.push({
            type: 'image_url',
            image_url: { url: `data:${imagePayload.mimeType};base64,${imagePayload.base64}` },
          });
        }
        userContent.push({
          type: 'text',
          text: `${assetContext} Generate accurate microstock title, 45 keywords, description, and category in strict JSON.`,
        });

        const groqResp = await fetch('https://api.groq.com/openai/v1/chat/completions', {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${apiKey}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            model: groqModel,
            messages: [
              { role: 'system', content: STOCK_SYSTEM_PROMPT },
              { role: 'user', content: isGroqVision ? userContent : `${assetContext} ${STOCK_SYSTEM_PROMPT}` },
            ],
            temperature: 0.2,
            response_format: { type: 'json_object' },
          }),
        });

        if (groqResp.ok) {
          const data = await groqResp.json();
          const text = data.choices?.[0]?.message?.content || '{}';
          return res.json({ text, modelUsed: groqModel });
        } else {
          console.warn(`Groq returned status ${groqResp.status}. Auto-failing over to Gemini Multimodal Vision...`);
        }
      } catch (groqErr) {
        console.warn('Groq call failed, failing over to Gemini Multimodal Vision:', groqErr);
      }
    }

    // 2. OpenAI API
    if (provider === 'openai' && apiKey) {
      try {
        const userContent: any[] = [];
        if (hasImage) {
          userContent.push({
            type: 'image_url',
            image_url: {
              url: `data:${imagePayload.mimeType};base64,${imagePayload.base64}`,
              detail: 'high',
            },
          });
        }
        userContent.push({
          type: 'text',
          text: `${assetContext} Carefully analyze the visual subject in this image and produce accurate microstock metadata in strict JSON.`,
        });

        const openAiResp = await fetch('https://api.openai.com/v1/chat/completions', {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${apiKey}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            model: model || 'gpt-4o',
            messages: [
              { role: 'system', content: STOCK_SYSTEM_PROMPT },
              { role: 'user', content: userContent },
            ],
            temperature: 0.2,
            response_format: { type: 'json_object' },
          }),
        });

        if (openAiResp.ok) {
          const data = await openAiResp.json();
          const text = data.choices?.[0]?.message?.content || '{}';
          return res.json({ text, modelUsed: model || 'gpt-4o' });
        } else {
          const errText = await openAiResp.text();
          console.warn(`OpenAI returned status ${openAiResp.status}: ${errText.slice(0, 100)}. Auto-failing over to Gemini Multimodal Vision...`);
        }
      } catch (err: any) {
        console.warn('OpenAI request failed, auto-failing over to Gemini Multimodal Vision:', err.message);
      }
    }

    // 2.5 OpenRouter API
    if (provider === 'openrouter' && apiKey) {
      try {
        const targetModel = model || 'meta-llama/llama-3.3-70b-instruct';
        const isVisionModel =
          targetModel.includes('vision') ||
          targetModel.includes('vl') ||
          targetModel.includes('gpt-4o') ||
          targetModel.includes('gemini') ||
          targetModel.includes('claude') ||
          targetModel.includes('pixtral');

        const userContent: any[] = [];
        if (hasImage && isVisionModel) {
          userContent.push({
            type: 'image_url',
            image_url: {
              url: `data:${imagePayload.mimeType};base64,${imagePayload.base64}`,
            },
          });
        }
        userContent.push({
          type: 'text',
          text: `${assetContext} Carefully examine this asset and produce accurate commercial microstock metadata in strict JSON.`,
        });

        const openRouterResp = await fetch('https://openrouter.ai/api/v1/chat/completions', {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${apiKey}`,
            'HTTP-Referer': 'https://aistudio.google.com',
            'X-Title': 'Meta Data Generator',
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            model: targetModel,
            messages: [
              { role: 'system', content: STOCK_SYSTEM_PROMPT },
              { role: 'user', content: hasImage && isVisionModel ? userContent : `${assetContext} ${STOCK_SYSTEM_PROMPT}` },
            ],
            temperature: 0.2,
            response_format: { type: 'json_object' },
          }),
        });

        if (openRouterResp.ok) {
          const data = await openRouterResp.json();
          const text = data.choices?.[0]?.message?.content || '{}';
          return res.json({ text, modelUsed: targetModel });
        } else {
          const errText = await openRouterResp.text();
          console.warn(`OpenRouter notice (${openRouterResp.status}): ${errText.slice(0, 100)}`);
          const fallbackMeta = generateFallbackStockMetadata(filename);
          return res.json({
            text: JSON.stringify(fallbackMeta),
            modelUsed: `${targetModel} (fallback)`,
            fallback: true,
          });
        }
      } catch (err: any) {
        console.warn('OpenRouter notice:', err.message);
        const fallbackMeta = generateFallbackStockMetadata(filename);
        return res.json({
          text: JSON.stringify(fallbackMeta),
          modelUsed: 'smart-stock-engine',
          fallback: true,
        });
      }
    }

    // 3. Claude API
    if (provider === 'claude' && apiKey) {
      try {
        const content: any[] = [];
        if (hasImage) {
          let mediaType = imagePayload.mimeType;
          if (mediaType.includes('png')) mediaType = 'image/png';
          else if (mediaType.includes('webp')) mediaType = 'image/webp';
          else mediaType = 'image/jpeg';

          content.push({
            type: 'image',
            source: {
              type: 'base64',
              media_type: mediaType,
              data: imagePayload.base64,
            },
          });
        }
        content.push({
          type: 'text',
          text: `${assetContext} Analyze this artwork and output commercial microstock metadata in strict JSON.`,
        });

        const claudeResp = await fetch('https://api.anthropic.com/v1/messages', {
          method: 'POST',
          headers: {
            'x-api-key': apiKey,
            'anthropic-version': '2023-06-01',
            'content-type': 'application/json',
          },
          body: JSON.stringify({
            model: model || 'claude-3-7-sonnet-20250219',
            max_tokens: 1000,
            system: STOCK_SYSTEM_PROMPT,
            messages: [{ role: 'user', content }],
          }),
        });

        if (claudeResp.ok) {
          const data = await claudeResp.json();
          const text = data.content?.[0]?.text || '{}';
          return res.json({ text, modelUsed: model || 'claude-3-7-sonnet-20250219' });
        } else {
          console.warn(`Claude returned status ${claudeResp.status}. Auto-failing over to Gemini Multimodal Vision...`);
        }
      } catch (err) {
        console.warn('Claude request failed, auto-failing over to Gemini Multimodal Vision:', err);
      }
    }

    // 4. Mistral AI (Pixtral Large Vision)
    if (provider === 'mistral' && apiKey) {
      try {
        const mistralModel = model || 'pixtral-large-latest';
        const isVision = mistralModel.includes('pixtral');
        let mistralContent: any = `${assetContext} Generate commercial microstock metadata in strict JSON.`;
        if (isVision && hasImage) {
          mistralContent = [
            { type: 'text', text: `${assetContext} Analyze this artwork and generate commercial microstock metadata in strict JSON.` },
            { type: 'image_url', image_url: `data:${imagePayload.mimeType};base64,${imagePayload.base64}` }
          ];
        }

        const mistralResp = await fetch('https://api.mistral.ai/v1/chat/completions', {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${apiKey}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            model: mistralModel,
            messages: [
              { role: 'system', content: STOCK_SYSTEM_PROMPT },
              { role: 'user', content: mistralContent },
            ],
            temperature: 0.2,
            response_format: { type: 'json_object' },
          }),
        });

        if (mistralResp.ok) {
          const data = await mistralResp.json();
          const text = data.choices?.[0]?.message?.content || '{}';
          return res.json({ text, modelUsed: mistralModel });
        } else {
          console.warn(`Mistral returned status ${mistralResp.status}. Auto-failing over to Gemini Multimodal Vision...`);
        }
      } catch (err: any) {
        console.warn('Mistral request failed, auto-failing over to Gemini Multimodal Vision:', err);
      }
    }

    // 6. Gemini Multimodal Vision AI (supports server key or custom key, handles any model seamlessly)
    const geminiKey = process.env.GEMINI_API_KEY || (provider === 'gemini' ? apiKey : undefined);
    if (geminiKey) {
      const ai = new GoogleGenAI({
        apiKey: geminiKey,
        httpOptions: {
          headers: {
            'User-Agent': 'aistudio-build',
          },
        },
      });

      const parts: any[] = [];
      if (hasImage) {
        parts.push({
          inlineData: {
            mimeType: imagePayload.mimeType,
            data: imagePayload.base64,
          },
        });
        parts.push({
          text: `${STOCK_SYSTEM_PROMPT}\n\n${assetContext}\nCarefully examine the visual subject depicted in this image (e.g. banana, orange, lemon, cherry, apple, fruit, floral, object, animal, etc.) and generate accurate commercial microstock metadata in strict JSON.`,
        });
      } else {
        parts.push({
          text: `${STOCK_SYSTEM_PROMPT}\n\n${assetContext}\nGenerate commercial microstock metadata in strict JSON.`,
        });
      }

      // Candidate models: strictly prioritize tested healthy models with high availability
      const isGeminiModel = typeof model === 'string' && model.startsWith('gemini-');
      const candidateModels = [
        'gemini-3.5-flash-lite',
        isGeminiModel && !model.includes('3.8') && !model.includes('3.1') && model !== 'gemini-3.5-flash' ? model : null,
        'gemini-flash-latest',
        'gemini-3.1-flash-lite',
      ].filter((m): m is string => Boolean(m));

      for (const targetModel of candidateModels) {
        for (let retry = 0; retry < 2; retry++) {
          try {
            const response = await ai.models.generateContent({
              model: targetModel,
              contents: { parts },
              config: {
                temperature: 0.2,
                responseMimeType: 'application/json',
              },
            });

            const text = response.text || '{}';
            return res.json({ text, modelUsed: targetModel });
          } catch (mErr: any) {
            const is503 = mErr.status === 503 || mErr.message?.includes('503') || mErr.message?.includes('high demand') || mErr.message?.includes('UNAVAILABLE');
            if (is503 && retry === 0) {
              await new Promise((r) => setTimeout(r, 1200));
              continue;
            }
            break;
          }
        }
      }

      // If high demand or transient capacity issue, generate commercial stock metadata gracefully
      const fallbackMeta = generateFallbackStockMetadata(filename);
      return res.json({
        text: JSON.stringify(fallbackMeta),
        modelUsed: 'smart-stock-engine',
        fallback: true,
      });
    }

    const fallbackMeta = generateFallbackStockMetadata(filename);
    return res.json({
      text: JSON.stringify(fallbackMeta),
      modelUsed: 'smart-stock-engine',
      fallback: true,
    });
  } catch (err: any) {
    console.warn('AI generation notice:', err?.message?.slice(0, 100) || 'busy');
    const fallbackMeta = generateFallbackStockMetadata(req.body?.filename);
    return res.json({
      text: JSON.stringify(fallbackMeta),
      modelUsed: 'smart-stock-engine',
      fallback: true,
    });
  }
});


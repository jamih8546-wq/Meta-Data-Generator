// Resilient commercial stock metadata fallback engine
function generateFallbackStockMetadata(filename?: string) {
  const raw = filename || 'artwork';
  const clean = raw
    .replace(/\.[^/.]+$/, '')
    .replace(/^\d+_\d+_/, '')
    .replace(/high-level-description-/gi, '')
    .replace(/a-photorealistic-?/gi, '')
    .replace(/a-hyper-realistic-?/gi, '')
    .replace(/\(\d+\)/g, '')
    .replace(/\[\d+\]/g, '')
    .replace(/copy/gi, '')
    .replace(/generated by [^)]+/gi, '')
    .replace(/stipple photocopy/gi, '')
    .replace(/stipple photo maker/gi, '')
    .replace(/\(subject:\s*[^)]+\)/gi, '')
    .replace(/^[\d\s\(\)\[\]_\-]+/, '')
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim() || 'Commercial Vector Artwork';

  const lower = raw.toLowerCase();
  let subject = clean;
  let category = 'Arts, Objects';

  if (lower.includes('banana')) {
    subject = 'Fresh Yellow Banana Fruit Bunch';
    category = 'Food and Drink';
  } else if (lower.includes('apple')) {
    subject = 'Fresh Red Apple Fruit with Green Leaf';
    category = 'Food and Drink';
  } else if (lower.includes('orange')) {
    subject = 'Fresh Juicy Orange Citrus Fruit';
    category = 'Food and Drink';
  } else if (lower.includes('lemon')) {
    subject = 'Fresh Yellow Lemon Citrus Slice';
    category = 'Food and Drink';
  } else if (lower.includes('cherry') || lower.includes('cherries')) {
    subject = 'Sweet Fresh Red Cherries on Stem';
    category = 'Food and Drink';
  } else if (lower.includes('strawberry')) {
    subject = 'Fresh Ripe Red Strawberry Berry';
    category = 'Food and Drink';
  } else if (lower.includes('fruit')) {
    subject = 'Fresh Organic Fruit Assortment';
    category = 'Food and Drink';
  } else if (lower.includes('flower') || lower.includes('floral') || lower.includes('lotus') || lower.includes('orchid') || lower.includes('dahlia')) {
    subject = 'Blooming Botanical Floral Blossom Illustration';
    category = 'Arts, Nature';
  }

  // CRITICAL: NEVER allow technique/style words like 'halftone' or 'stipple' to become the title subject!
  const isStyleOnly =
    subject.toLowerCase() === 'halftone' ||
    subject.toLowerCase() === 'stipple' ||
    subject.toLowerCase() === 'artwork' ||
    subject.toLowerCase() === 'vector' ||
    subject.toLowerCase() === 'illustration' ||
    subject.trim().length < 3;

  if (isStyleOnly) {
    subject = 'Detailed Vintage Botanical Fruit Illustration';
    category = 'Food and Drink';
  }

  const title = `${subject} Isolated on White Background`.slice(0, 80);
  const keywords = Array.from(new Set([
    ...clean.toLowerCase().split(' ').filter(w => w.length > 2),
    'illustration', 'vector', 'isolated', 'white background', 'graphic design', 'clipart', 'modern',
    'digital art', 'commercial', 'element', 'fresh', 'nature', 'food', 'healthy', 'organic',
    'ingredient', 'nutrition', 'sweet', 'ripe', 'juicy', 'closeup', 'object', 'icon', 'symbol',
    'artistic', 'minimalist', 'clean', 'eps10', 'high quality', 'stock vector', 'decorative',
    'creative', 'poster', 'print', 'drawing', 'texture', 'pattern', 'detail', 'vibrant', 'color',
    'culinary', 'produce', 'diet', 'agriculture'
  ])).filter(Boolean).slice(0, 48).join(', ');

  const description = `A high quality commercial illustration of ${subject.toLowerCase()} cleanly isolated on a white background for microstock and design projects.`;

  return {
    title,
    keywords,
    description,
    category,
  };
}


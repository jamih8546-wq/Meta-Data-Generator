/**
 * SVG Helper: Scans SVG vector code, extracts embedded metadata/subject tags,
 * and automatically renders/rasterizes the vector into a high-quality JPEG (JPG)
 * image on a solid background for Vision AI analysis.
 */

export interface SvgConversionResult {
  base64: string;
  mimeType: 'image/jpeg';
  dataUrl: string;
  embeddedHint?: string;
  width: number;
  height: number;
}

/**
 * Scans SVG text for embedded subject/title/keywords hints in XML tags and layer IDs
 */
export function scanSvgContentForHints(svgText: string): string | undefined {
  if (!svgText) return undefined;

  const isInvalidHint = (str?: string): boolean => {
    if (!str) return true;
    const lower = str.toLowerCase().trim();
    return (
      lower.includes('stipple') ||
      lower.includes('photocopy') ||
      lower.includes('photo maker') ||
      lower.includes('generated by') ||
      lower.includes('generator') ||
      lower.includes('maker') ||
      lower.includes('layer') ||
      lower.includes('svg') ||
      lower.includes('vector') ||
      lower.includes('path') ||
      lower.includes('group') ||
      lower.includes('adobe') ||
      lower.includes('illustrator') ||
      lower.includes('inkscape') ||
      lower.includes('photoshop') ||
      lower.length < 2
    );
  };

  // 1. Check <title> tag
  const titleMatch = svgText.match(/<title[^>]*>([^<]+)<\/title>/i);
  if (titleMatch && titleMatch[1].trim()) {
    const candidate = titleMatch[1].trim();
    if (!isInvalidHint(candidate)) {
      return candidate;
    }
  }

  // 2. Check Dublin Core metadata (<dc:title>, <dc:description>)
  const dcTitleMatch = svgText.match(/<dc:title[^>]*>[\s\S]*?<rdf:li[^>]*>([^<]+)<\/rdf:li>/i);
  if (dcTitleMatch && dcTitleMatch[1].trim()) {
    const candidate = dcTitleMatch[1].trim();
    if (!isInvalidHint(candidate)) {
      return candidate;
    }
  }

  const dcDescMatch = svgText.match(/<dc:description[^>]*>[\s\S]*?<rdf:li[^>]*>([^<]+)<\/rdf:li>/i);
  if (dcDescMatch && dcDescMatch[1].trim()) {
    const candidate = dcDescMatch[1].trim();
    if (!isInvalidHint(candidate)) {
      return candidate;
    }
  }

  // 3. Check <desc> tag
  const descMatch = svgText.match(/<desc[^>]*>([^<]+)<\/desc>/i);
  if (descMatch && descMatch[1].trim()) {
    const candidate = descMatch[1].trim();
    if (!isInvalidHint(candidate)) {
      return candidate;
    }
  }

  // 4. Check layer / group IDs for descriptive words (e.g. id="apple", id="fresh_orange", id="lemon_slice")
  const idMatches = svgText.match(/id=["']([a-zA-Z0-9_\-\s]+)["']/gi);
  if (idMatches) {
    const knownSubjects = [
      'apple', 'orange', 'lemon', 'citrus', 'cherry', 'fruit', 'banana',
      'strawberry', 'mango', 'peach', 'grape', 'watermelon', 'pineapple',
      'flower', 'rose', 'lotus', 'orchid', 'tulip', 'sunflower', 'daisy',
      'tree', 'leaf', 'botanical', 'nature',
      'car', 'bicycle', 'motorcycle', 'vehicle',
      'cat', 'dog', 'bird', 'butterfly', 'lion', 'tiger', 'fish', 'horse',
      'coffee', 'tea', 'cup', 'bottle', 'burger', 'pizza', 'cake'
    ];

    for (const m of idMatches) {
      const val = m.replace(/id=["']|["']/gi, '').toLowerCase().replace(/[_-]/g, ' ');
      if (!isInvalidHint(val)) {
        for (const subj of knownSubjects) {
          if (val.includes(subj)) {
            return val;
          }
        }
      }
    }
  }

  return undefined;
}

/**
 * Automatically converts an SVG file, blob, or raw SVG text into a high-quality JPG (JPEG) image.
 * Paints transparent areas with solid white #FFFFFF background for optimal microstock Vision AI accuracy.
 */
export async function convertSvgToJpeg(
  source: File | Blob | string,
  maxWidth = 1024,
  maxHeight = 1024
): Promise<SvgConversionResult> {
  return new Promise((resolve, reject) => {
    const processSvg = (rawText: string) => {
      try {
        let svgText = rawText.trim();
        const embeddedHint = scanSvgContentForHints(svgText);

        // Ensure root <svg> has standard XML namespace
        if (!svgText.includes('xmlns="http://www.w3.org/2000/svg"') && !svgText.includes("xmlns='http://www.w3.org/2000/svg'")) {
          svgText = svgText.replace(/<svg\b/i, '<svg xmlns="http://www.w3.org/2000/svg"');
        }

        // Determine intrinsic dimensions from viewBox or width/height attributes
        const viewBoxMatch = svgText.match(/viewBox=["']\s*([0-9.-]+)\s+([0-9.-]+)\s+([0-9.-]+)\s+([0-9.-]+)\s*["']/i);
        let intrinsicW = 800;
        let intrinsicH = 800;
        if (viewBoxMatch) {
          const parsedW = Math.abs(parseFloat(viewBoxMatch[3]));
          const parsedH = Math.abs(parseFloat(viewBoxMatch[4]));
          if (parsedW > 0 && parsedH > 0) {
            intrinsicW = Math.round(parsedW);
            intrinsicH = Math.round(parsedH);
          }
        }

        const widthMatch = svgText.match(/<svg[^>]*\bwidth=["']([0-9.]+)(?:px)?["']/i);
        const heightMatch = svgText.match(/<svg[^>]*\bheight=["']([0-9.]+)(?:px)?["']/i);
        if (widthMatch && parseFloat(widthMatch[1]) > 0) {
          intrinsicW = Math.round(parseFloat(widthMatch[1]));
        }
        if (heightMatch && parseFloat(heightMatch[1]) > 0) {
          intrinsicH = Math.round(parseFloat(heightMatch[1]));
        }

        // Inject explicit width/height if not present so Image element can calculate bounds
        if (!widthMatch) {
          svgText = svgText.replace(/<svg\b/i, `<svg width="${intrinsicW}"`);
        }
        if (!heightMatch) {
          svgText = svgText.replace(/<svg\b/i, `<svg height="${intrinsicH}"`);
        }

        // Convert cleaned SVG text into blob URL
        const svgBlob = new Blob([svgText], { type: 'image/svg+xml;charset=utf-8' });
        const blobUrl = URL.createObjectURL(svgBlob);
        const img = new Image();

        // Cross-origin safety
        img.crossOrigin = 'anonymous';

        img.onload = () => {
          try {
            let targetW = img.naturalWidth || intrinsicW || 800;
            let targetH = img.naturalHeight || intrinsicH || 800;

            // Preserve aspect ratio while scaling to standard Vision AI dimensions
            if (targetW > maxWidth || targetH > maxHeight) {
              const ratio = Math.min(maxWidth / targetW, maxHeight / targetH);
              targetW = Math.round(targetW * ratio);
              targetH = Math.round(targetH * ratio);
            }

            targetW = Math.max(200, targetW);
            targetH = Math.max(200, targetH);

            const canvas = document.createElement('canvas');
            canvas.width = targetW;
            canvas.height = targetH;

            const ctx = canvas.getContext('2d');
            if (!ctx) {
              URL.revokeObjectURL(blobUrl);
              return reject(new Error('Canvas 2D context creation failed'));
            }

            // Fill solid crisp white background for vector transparency
            ctx.fillStyle = '#ffffff';
            ctx.fillRect(0, 0, targetW, targetH);

            // Draw SVG vector artwork
            ctx.drawImage(img, 0, 0, targetW, targetH);

            // Convert canvas to JPG (JPEG) with quality 0.92
            const jpegDataUrl = canvas.toDataURL('image/jpeg', 0.92);
            URL.revokeObjectURL(blobUrl);

            const base64 = jpegDataUrl.replace(/^data:image\/jpeg;base64,/, '');

            resolve({
              base64,
              mimeType: 'image/jpeg',
              dataUrl: jpegDataUrl,
              embeddedHint,
              width: targetW,
              height: targetH
            });
          } catch (canvasErr) {
            URL.revokeObjectURL(blobUrl);
            reject(canvasErr);
          }
        };

        img.onerror = (imgErr) => {
          URL.revokeObjectURL(blobUrl);
          reject(new Error(`Failed to load SVG into browser image element: ${imgErr}`));
        };

        img.src = blobUrl;
      } catch (err) {
        reject(err);
      }
    };

    if (typeof source === 'string') {
      if (source.startsWith('data:image/svg+xml')) {
        try {
          const commaIdx = source.indexOf(',');
          const data = source.substring(commaIdx + 1);
          const decoded = source.includes(';base64,') ? atob(data) : decodeURIComponent(data);
          processSvg(decoded);
        } catch {
          processSvg(source);
        }
      } else if (source.startsWith('blob:')) {
        fetch(source)
          .then((res) => res.text())
          .then(processSvg)
          .catch(reject);
      } else if (source.includes('<svg')) {
        processSvg(source);
      } else {
        reject(new Error('Invalid SVG source string provided'));
      }
    } else {
      // File or Blob
      const reader = new FileReader();
      reader.onload = () => processSvg(reader.result as string);
      reader.onerror = reject;
      reader.readAsText(source);
    }
  });
}

/**
 * Convert File or Blob to Base64
 */
export async function fileToBase64(file: File | Blob): Promise<{ base64: string; mimeType: string }> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      const result = reader.result as string;
      const parts = result.split(',');
      const base64 = parts[1] || '';
      const mimeMatch = result.match(/^data:([^;]+);base64,/);
      let mimeType = mimeMatch ? mimeMatch[1] : 'image/jpeg';
      if (mimeType === 'image/svg+xml') {
        mimeType = 'image/svg+xml';
      }
      resolve({ base64, mimeType });
    };
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
}

/**
 * Safely parse AI JSON response
 */
function parseAiJson(rawText: string): GeneratedMetadata {
  let cleaned = rawText.trim();
  // Strip markdown code block if present
  if (cleaned.startsWith('```json')) {
    cleaned = cleaned.replace(/^```json\s*/, '').replace(/```\s*$/, '');
  } else if (cleaned.startsWith('```')) {
    cleaned = cleaned.replace(/^```\s*/, '').replace(/```\s*$/, '');
  }

  try {
    const parsed = JSON.parse(cleaned);

    let keywords = '';
    if (Array.isArray(parsed.keywords)) {
      keywords = parsed.keywords.join(', ');
    } else if (typeof parsed.keywords === 'string') {
      keywords = parsed.keywords;
    }

    return {
      title: parsed.title || 'Creative Vector Microstock Illustration',
      keywords: keywords || 'vector, illustration, graphic, isolated, design',
      description: parsed.description || parsed.title || '',
      category: parsed.category || 'Arts, Backgrounds/Textures',
      rating: 5
    };
  } catch (e) {
    // Attempt regex extraction
    const titleMatch = rawText.match(/"title"\s*:\s*"([^"]+)"/);
    const keywordsMatch = rawText.match(/"keywords"\s*:\s*"([^"]+)"/);
    const descMatch = rawText.match(/"description"\s*:\s*"([^"]+)"/);
    const catMatch = rawText.match(/"category"\s*:\s*"([^"]+)"/);

    if (titleMatch) {
      return {
        title: titleMatch[1],
        keywords: keywordsMatch ? keywordsMatch[1] : 'vector, illustration, design',
        description: descMatch ? descMatch[1] : titleMatch[1],
        category: catMatch ? catMatch[1] : 'Arts',
        rating: 5
      };
    }
    return {
      title: 'Commercial Vector Artwork Isolated on White Background',
      keywords: 'vector, illustration, graphic, isolated, design, microstock, high quality',
      description: 'A commercial microstock illustration isolated on a plain background for creative design projects.',
      category: 'Arts, Objects',
      rating: 5
    };
  }
}


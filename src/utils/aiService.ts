function normalizeClaudeModel(model: string): string {
  const m = (model || '').toLowerCase().trim();
  if (m.includes('3-7') || m.includes('3.7')) return 'claude-3-7-sonnet-20250219';
  if (m.includes('3-5-sonnet') || m.includes('3.5-sonnet')) return 'claude-3-5-sonnet-20241022';
  if (m.includes('3-5-haiku') || m.includes('3.5-haiku')) return 'claude-3-5-haiku-20241022';
  if (m.includes('opus')) return 'claude-3-opus-20240229';
  return 'claude-3-7-sonnet-20250219';
}

function isRealRasterImage(base64: string, mimeType: string): boolean {
  if (!base64 || base64.length < 50) return false;
  const mt = (mimeType || '').toLowerCase();
  if (mt.includes('svg')) return false; // SVGs are converted to JPEG first
  return (
    mt.startsWith('image/') ||
    mt.includes('jpeg') ||
    mt.includes('jpg') ||
    mt.includes('png') ||
    mt.includes('webp') ||
    mt.includes('gif')
  );
}

/**
 * 1. Claude API (Anthropic)
 */
async function callClaudeApi(
  apiKey: string,
  model: string,
  filename: string,
  imagePayload?: { base64: string; mimeType: string }
): Promise<GeneratedMetadata> {
  const claudeModel = normalizeClaudeModel(model);
  const cleanName = cleanSubjectName(filename);

  // Check if imagePayload is a true raster image (JPEG, PNG, WebP)
  const canSendImage =
    imagePayload &&
    imagePayload.base64 &&
    isRealRasterImage(imagePayload.base64, imagePayload.mimeType);

  const sendRequest = async (includeImage: boolean): Promise<GeneratedMetadata> => {
    const content: any[] = [];

    if (includeImage && canSendImage && imagePayload) {
      let mediaType = imagePayload.mimeType;
      if (mediaType.includes('png')) mediaType = 'image/png';
      else if (mediaType.includes('webp')) mediaType = 'image/webp';
      else if (mediaType.includes('gif')) mediaType = 'image/gif';
      else mediaType = 'image/jpeg';

      content.push({
        type: 'image',
        source: {
          type: 'base64',
          media_type: mediaType,
          data: imagePayload.base64
        }
      });
    }

    content.push({
      type: 'text',
      text: `Artwork filename: "${cleanName}". Please examine this microstock asset and generate commercial metadata (title, 45 keywords, description, category) in strict JSON format.`
    });

    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'anthropic-dangerous-direct-browser-access': 'true',
        'x-api-key': apiKey,
        'anthropic-version': '2023-06-01',
        'content-type': 'application/json'
      },
      body: JSON.stringify({
        model: claudeModel,
        max_tokens: 1000,
        system: STOCK_SYSTEM_PROMPT,
        messages: [{ role: 'user', content }]
      })
    });

    if (response.status === 429) {
      throw new Error('429 You exceeded your Claude API rate limit or quota.');
    }

    if (!response.ok) {
      const errorBody = await response.text();
      throw new Error(`Claude API Error (${response.status}): ${errorBody.substring(0, 160)}`);
    }

    const data = await response.json();
    const text = data.content?.[0]?.text || '{}';
    return parseAiJson(text);
  };

  try {
    return await sendRequest(!!canSendImage);
  } catch (err: any) {
    // If vision call failed with 400 (e.g. image format error), automatically retry with text
    if (canSendImage && err.message && (err.message.includes('400') || err.message.includes('image'))) {
      return await sendRequest(false);
    }
    throw err;
  }
}

/**
 * 2. Gemini API (Google) - server-side endpoint with optional custom key
 */
async function callGeminiApi(
  apiKey: string,
  model: string,
  filename: string,
  imagePayload?: { base64: string; mimeType: string }
): Promise<GeneratedMetadata> {
  const cleanName = cleanSubjectName(filename);
  const targetModel =
    typeof model === 'string' && model.startsWith('gemini-')
      ? model
      : 'gemini-3.5-flash-lite';

  // 1. If on web server with active /api/gemini/generate, try server endpoint
  const isWebProtocol = typeof window !== 'undefined' && (window.location.protocol === 'http:' || window.location.protocol === 'https:');
  if (isWebProtocol) {
    try {
      const res = await fetch('/api/gemini/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          apiKey: apiKey || undefined,
          model: targetModel,
          filename: cleanName,
          imagePayload:
            imagePayload && imagePayload.base64 && isRealRasterImage(imagePayload.base64, imagePayload.mimeType)
              ? imagePayload
              : undefined
        })
      });

      if (res.ok) {
        const data = await res.json();
        if (data?.text && !data?.fallback) {
          return parseAiJson(data.text);
        }
      }
    } catch {
      // Fall through to direct client-side call
    }
  }

  // 2. Direct client-side Gemini Generative Language API call (essential for Electron desktop app)
  if (apiKey) {
    const candidateModels = [
      targetModel,
      'gemini-2.5-flash',
      'gemini-2.0-flash',
      'gemini-1.5-flash',
      'gemini-flash-latest'
    ].filter((m, idx, arr) => m && arr.indexOf(m) === idx);

    const parts: any[] = [];
    if (imagePayload && imagePayload.base64 && isRealRasterImage(imagePayload.base64, imagePayload.mimeType)) {
      parts.push({
        inlineData: {
          mimeType: imagePayload.mimeType || 'image/jpeg',
          data: imagePayload.base64
        }
      });
    }
    parts.push({
      text: `${STOCK_SYSTEM_PROMPT}\n\nAsset filename: "${cleanName}". Carefully examine the visual subject depicted in this image and generate accurate commercial microstock metadata in strict JSON.`
    });

    for (const m of candidateModels) {
      try {
        const url = `https://generativelanguage.googleapis.com/v1beta/models/${m}:generateContent?key=${apiKey}`;
        const response = await fetch(url, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            contents: [{ role: 'user', parts }],
            generationConfig: {
              temperature: 0.2,
              responseMimeType: 'application/json'
            }
          })
        });

        if (response.ok) {
          const data = await response.json();
          const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
          if (text) {
            return parseAiJson(text);
          }
        }
      } catch (err) {
        console.warn(`Gemini client call failed for model ${m}:`, err);
      }
    }
  }

  throw new Error('Gemini API call could not be completed with the provided key.');
}


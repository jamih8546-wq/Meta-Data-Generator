/**
 * Accurately extracts a visual image representation for vision AI models.
 * - If file is an SVG vector: renders SVG onto canvas and converts it to high-quality JPEG
 *   with solid white background so Vision AI (GPT-4o, Gemini, Claude) accurately detects
 *   colors, shapes, fruits, objects, and compositions. Also scans SVG XML tags for hints.
 * - If file is an EPS vector: extracts embedded preview raster thumbnail.
 * - If file is a raster image: returns base64 image.
 */
export async function extractVisualPayload(item: MetadataItem): Promise<{ base64: string; mimeType: string } | undefined> {
  try {
    const lowerName = (item.originalName || item.filename || '').toLowerCase();
    const isSvg =
      item.fileType === 'svg' ||
      lowerName.endsWith('.svg') ||
      (item.fileBlob && item.fileBlob.type.includes('svg')) ||
      Boolean(item.svgContent) ||
      (item.dataUrl && (item.dataUrl.includes('image/svg') || item.dataUrl.includes('.svg')));

    // 1. SVG Vector Artwork: automatically scan and convert to crisp high-res JPG (JPEG)
    if (isSvg) {
      const source = item.fileBlob || item.svgContent || item.dataUrl;
      if (source) {
        try {
          const res = await convertSvgToJpeg(source);
          if (res.embeddedHint && !item.subjectHint) {
            item.subjectHint = res.embeddedHint;
          }
          if (!item.dataUrl || item.dataUrl.startsWith('blob:') || item.dataUrl.includes('image/svg')) {
            item.dataUrl = res.dataUrl;
          }
          return {
            base64: res.base64,
            mimeType: 'image/jpeg'
          };
        } catch (svgErr) {
          console.warn('SVG-to-JPEG conversion notice:', svgErr);
        }
      }
    }

    // 2. If item already has a raster image dataUrl (JPEG, PNG, WebP)
    if (item.dataUrl) {
      if (
        item.dataUrl.startsWith('data:image/jpeg') ||
        item.dataUrl.startsWith('data:image/jpg') ||
        item.dataUrl.startsWith('data:image/png') ||
        item.dataUrl.startsWith('data:image/webp')
      ) {
        const match = item.dataUrl.match(/^data:([^;]+);base64,(.+)$/);
        if (match) {
          return { mimeType: match[1], base64: match[2] };
        }
      } else if (item.dataUrl.startsWith('blob:')) {
        try {
          const res = await fetch(item.dataUrl);
          const blob = await res.blob();
          if (blob.type.includes('svg')) {
            const svgRes = await convertSvgToJpeg(blob);
            return { base64: svgRes.base64, mimeType: 'image/jpeg' };
          }
          return await fileToBase64(blob);
        } catch (blobErr) {
          console.warn('Could not read blob dataUrl:', blobErr);
        }
      }
    }

    if (item.fileBlob) {
      // 3. EPS vector: extract embedded raster thumbnail
      const isEps = item.fileType === 'eps' || lowerName.endsWith('.eps') || lowerName.endsWith('.ai');
      if (isEps) {
        const epsInfo = await extractEpsInfo(item.fileBlob);
        if (epsInfo.hasPreview && epsInfo.previewBase64 && epsInfo.previewMimeType) {
          return { base64: epsInfo.previewBase64, mimeType: epsInfo.previewMimeType };
        }
        return undefined;
      }

      // 4. Standard raster images (JPEG, PNG, WEBP, GIF, etc.)
      const isRaster =
        item.fileBlob.type.startsWith('image/') ||
        lowerName.endsWith('.jpg') ||
        lowerName.endsWith('.png') ||
        lowerName.endsWith('.webp');

      if (isRaster) {
        return await fileToBase64(item.fileBlob);
      }
    }
  } catch (err) {
    console.warn('Could not extract visual payload:', err);
  }
  return undefined;
}

/**
 * 6. High-Precision Smart Fallback (when no key provided or offline)
 */
export function generateLocalStockMetadata(
  filename: string,
  options: GenerationOptions
): GeneratedMetadata {
  const cleanSubject = cleanSubjectName(filename);
  const cleanLower = filename.toLowerCase();

  let subject = cleanSubject;
  let technique = 'modern graphic illustration';
  let category = 'Arts, Objects';

  if (cleanLower.includes('halftone')) {
    technique = 'vintage halftone pattern';
  } else if (cleanLower.includes('stipple')) {
    technique = 'intricate stipple engraving';
  }

  if (cleanLower.includes('apple')) {
    subject = 'fresh red apple fruit';
    category = 'Food and Drink';
  } else if (cleanLower.includes('orange')) {
    subject = 'fresh citrus orange fruit';
    category = 'Food and Drink';
  } else if (cleanLower.includes('lemon')) {
    subject = 'fresh yellow lemon citrus';
    category = 'Food and Drink';
  } else if (cleanLower.includes('citrus')) {
    subject = 'fresh citrus fruit slice';
    category = 'Food and Drink';
  } else if (cleanLower.includes('cherry') || cleanLower.includes('cherries')) {
    subject = 'sweet fresh red cherries';
    category = 'Food and Drink';
  } else if (cleanLower.includes('strawberry')) {
    subject = 'fresh ripe strawberry berry';
    category = 'Food and Drink';
  } else if (cleanLower.includes('banana')) {
    subject = 'fresh yellow tropical banana';
    category = 'Food and Drink';
  } else if (cleanLower.includes('fruit')) {
    subject = 'fresh organic fruit';
    category = 'Food and Drink';
  } else if (cleanLower.includes('lotus')) {
    subject = 'lotus flower bloom';
    category = 'Arts, Nature';
  } else if (cleanLower.includes('dahlia')) {
    subject = 'dahlia floral head';
    category = 'Arts, Nature';
  } else if (cleanLower.includes('orchid')) {
    subject = 'exotic orchid flower';
    category = 'Arts, Objects';
  } else if (cleanLower.includes('flower') || cleanLower.includes('floral') || cleanLower.includes('botanical')) {
    subject = 'botanical flower blossom';
    category = 'Arts, Nature';
  } else if (cleanSubject.toLowerCase() === 'stipple' || cleanSubject.toLowerCase() === 'halftone') {
    subject = `${technique} vector design element`;
    category = 'Arts, Objects';
  } else {
    subject = `${cleanSubject} artwork element`;
  }

  // Capitalize properly
  const formattedTitle = `${subject.charAt(0).toUpperCase() + subject.slice(1)} isolated on white background`;
  const keywordsList = extractKeywordsFromFilename(filename);

  const description = options.description
    ? `A detailed ${technique} rendering of ${subject}, cleanly isolated on a plain background for commercial graphic design and print projects.`
    : '';

  return {
    title: formattedTitle.slice(0, 80),
    keywords: keywordsList.join(', '),
    description,
    category,
    rating: 5
  };
}

/**
 * Generate metadata using active provider or fallback logic
 */
export async function generateMetadataForFile(
  item: MetadataItem,
  config: ApiConfig,
  options: GenerationOptions
): Promise<GeneratedMetadata> {
  const provider = config.provider || 'gemini';

  const currentKey =
    provider === 'gemini'
      ? config.geminiKey
      : provider === 'openai'
      ? config.openaiKey
      : provider === 'openrouter'
      ? config.openrouterKey
      : provider === 'claude'
      ? config.claudeKey
      : provider === 'groq'
      ? config.groqKey
      : provider === 'mistral'
      ? config.mistralKey
      : '';

  // Extract visual image payload (renders SVG to canvas PNG, or converts image file)
  const imagePayload = await extractVisualPayload(item);

  // If user provided a subject hint or EPS has embedded DSC/XMP/layer subject, extract it as hint
  let effectiveFilename = item.filename;
  if (item.subjectHint && item.subjectHint.trim()) {
    effectiveFilename = `${item.filename} (Subject: ${item.subjectHint.trim()})`;
  } else if (item.fileType === 'eps' && item.fileBlob) {
    try {
      const epsInfo = await extractEpsInfo(item.fileBlob);
      const hint = epsInfo.subject || epsInfo.title;
      if (hint && !effectiveFilename.toLowerCase().includes(hint.toLowerCase())) {
        effectiveFilename = `${effectiveFilename} (Subject: ${hint})`;
      }
    } catch (e) {
      // ignore
    }
  }

  // 1. In web environment with backend proxy running, try server endpoint first
  const isWebProtocol =
    typeof window !== 'undefined' &&
    (window.location.protocol === 'http:' || window.location.protocol === 'https:');

  if (isWebProtocol) {
    try {
      const res = await fetch('/api/ai/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          provider,
          model: config.activeModel,
          apiKey: currentKey || undefined,
          filename: effectiveFilename,
          imagePayload
        })
      });

      if (res.ok) {
        const data = await res.json();
        if (data?.text && !data?.fallback) {
          return parseAiJson(data.text);
        }
      }
    } catch (serverErr: any) {
      console.warn('Server AI endpoint notice (routing to direct client Vision API):', serverErr?.message || serverErr);
    }
  }

  // 2. Direct client-side Vision API execution (essential for Electron desktop .exe app)
  if (currentKey && currentKey.trim()) {
    try {
      const cleanKey = currentKey.trim();
      if (provider === 'gemini') {
        return await callGeminiApi(
          cleanKey,
          config.geminiModel || config.activeModel || 'gemini-3.5-flash-lite',
          effectiveFilename,
          imagePayload
        );
      } else if (provider === 'openai') {
        return await callOpenAiApi(
          cleanKey,
          config.openaiModel || config.activeModel || 'gpt-4o',
          effectiveFilename,
          imagePayload
        );
      } else if (provider === 'openrouter') {
        return await callOpenRouterApi(
          cleanKey,
          config.openrouterModel || config.activeModel || 'google/gemini-2.0-flash-001',
          effectiveFilename,
          imagePayload
        );
      } else if (provider === 'claude') {
        return await callClaudeApi(
          cleanKey,
          config.claudeModel || config.activeModel || 'claude-3-7-sonnet-20250219',
          effectiveFilename,
          imagePayload
        );
      } else if (provider === 'groq') {
        return await callGroqApi(
          cleanKey,
          config.groqModel || config.activeModel || 'llama-3.2-11b-vision-preview',
          effectiveFilename,
          imagePayload
        );
      } else if (provider === 'mistral') {
        return await callMistralApi(
          cleanKey,
          config.mistralModel || config.activeModel || 'pixtral-large-latest',
          effectiveFilename,
          imagePayload
        );
      }
    } catch (clientApiErr: any) {
      console.warn(`Direct ${provider} Vision API execution notice:`, clientApiErr?.message || clientApiErr);
    }
  }

  // 3. Resilient fallback to smart stock metadata engine
  return generateLocalStockMetadata(effectiveFilename, options);
}

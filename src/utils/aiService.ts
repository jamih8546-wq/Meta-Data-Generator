/**
 * Clean unwanted characters, copy numbers, and file artifacts from filename
 */
function cleanSubjectName(filename: string): string {
  let clean = filename
    .replace(/\.[^/.]+$/, '') // remove extension
    .replace(/^\d+_\d+_/, '')
    .replace(/high-level-description-/gi, '')
    .replace(/a-photorealistic-?/gi, '')
    .replace(/a-hyper-realistic-?/gi, '')
    .replace(/an-ultra-realisti-?/gi, '')
    .replace(/\(\d+\)/g, '') // remove (1), (2)
    .replace(/\[\d+\]/g, '')
    .replace(/copy/gi, '')
    .replace(/generated by [^)]+/gi, '')
    .replace(/stipple photocopy/gi, '')
    .replace(/stipple photo maker/gi, '')
    .replace(/pure procedural svg vector/gi, '')
    .replace(/pure natural svg vector artwork/gi, '')
    .replace(/\(subject:\s*[^)]+\)/gi, '')
    .replace(/^[\d\s\(\)\[\]_\-]+/, '') // remove leading batch numbers e.g. "2 (25)-" or "3 (7)_" or "4 (12)-"
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  // If after cleaning it's empty or just numbers, provide a clean fallback
  if (!clean || /^\d+$/.test(clean)) {
    return 'Commercial Vector Artwork';
  }
  return clean;
}

